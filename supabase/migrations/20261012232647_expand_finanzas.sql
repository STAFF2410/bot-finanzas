-- La desactivacion de RLS permite acceso sin politicas a los roles que tengan
-- permisos SQL. Reactivala y define politicas antes de exponer estas tablas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.cuentas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  tipo_moneda text NOT NULL,
  saldo_actual numeric(20, 6) NOT NULL DEFAULT 0
);

ALTER TABLE public.cuentas
  ADD COLUMN IF NOT EXISTS nombre text,
  ADD COLUMN IF NOT EXISTS tipo_moneda text,
  ADD COLUMN IF NOT EXISTS saldo_actual numeric(20, 6) NOT NULL DEFAULT 0;

DO $$
DECLARE
  cuenta_id_type text;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod)
    INTO cuenta_id_type
  FROM pg_attribute AS a
  JOIN pg_class AS c ON c.oid = a.attrelid
  JOIN pg_namespace AS n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    AND c.relname = 'cuentas'
    AND a.attname = 'id'
    AND NOT a.attisdropped;

  IF cuenta_id_type IS NULL THEN
    RAISE EXCEPTION 'public.cuentas debe tener una columna id para crear las claves foraneas';
  END IF;

  EXECUTE format(
    'CREATE TABLE IF NOT EXISTS public.transacciones (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tipo text NOT NULL,
      monto_origen numeric(20, 6) NOT NULL,
      moneda_origen text NOT NULL,
      monto_destino numeric(20, 6),
      moneda_destino text,
      tasa_cambio numeric(24, 10),
      cuenta_origen_id %s REFERENCES public.cuentas(id) ON DELETE RESTRICT,
      cuenta_destino_id %s REFERENCES public.cuentas(id) ON DELETE RESTRICT,
      categoria text,
      descripcion text,
      fecha timestamptz NOT NULL DEFAULT now(),
      estado text NOT NULL DEFAULT ''registrada'',
      raw_prompt text
    )',
    cuenta_id_type,
    cuenta_id_type
  );

  EXECUTE format(
    'ALTER TABLE public.transacciones
      ADD COLUMN IF NOT EXISTS cuenta_origen_id %s,
      ADD COLUMN IF NOT EXISTS cuenta_destino_id %s',
    cuenta_id_type,
    cuenta_id_type
  );
END
$$;

ALTER TABLE public.transacciones
  ADD COLUMN IF NOT EXISTS tipo text,
  ADD COLUMN IF NOT EXISTS monto_origen numeric(20, 6),
  ADD COLUMN IF NOT EXISTS moneda_origen text,
  ADD COLUMN IF NOT EXISTS monto_destino numeric(20, 6),
  ADD COLUMN IF NOT EXISTS moneda_destino text,
  ADD COLUMN IF NOT EXISTS tasa_cambio numeric(24, 10),
  ADD COLUMN IF NOT EXISTS categoria text,
  ADD COLUMN IF NOT EXISTS descripcion text,
  ADD COLUMN IF NOT EXISTS fecha timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS estado text NOT NULL DEFAULT 'registrada',
  ADD COLUMN IF NOT EXISTS raw_prompt text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.transacciones'::regclass
      AND conname = 'transacciones_cuenta_origen_id_fkey'
  ) THEN
    ALTER TABLE public.transacciones
      ADD CONSTRAINT transacciones_cuenta_origen_id_fkey
      FOREIGN KEY (cuenta_origen_id) REFERENCES public.cuentas(id)
      ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.transacciones'::regclass
      AND conname = 'transacciones_cuenta_destino_id_fkey'
  ) THEN
    ALTER TABLE public.transacciones
      ADD CONSTRAINT transacciones_cuenta_destino_id_fkey
      FOREIGN KEY (cuenta_destino_id) REFERENCES public.cuentas(id)
      ON DELETE RESTRICT;
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.deudas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto numeric(20, 6) NOT NULL,
  acreedor_deudor text NOT NULL,
  fecha_limite date,
  estado text NOT NULL DEFAULT 'pendiente'
);

ALTER TABLE public.deudas
  ADD COLUMN IF NOT EXISTS monto numeric(20, 6),
  ADD COLUMN IF NOT EXISTS acreedor_deudor text,
  ADD COLUMN IF NOT EXISTS fecha_limite date,
  ADD COLUMN IF NOT EXISTS estado text NOT NULL DEFAULT 'pendiente';

CREATE TABLE IF NOT EXISTS public.memoria_chat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id bigint NOT NULL,
  rol text NOT NULL CHECK (rol IN ('user', 'bot')),
  mensaje text NOT NULL,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.memoria_chat
  ADD COLUMN IF NOT EXISTS message_id bigint,
  ADD COLUMN IF NOT EXISTS rol text,
  ADD COLUMN IF NOT EXISTS mensaje text,
  ADD COLUMN IF NOT EXISTS fecha_creacion timestamptz NOT NULL DEFAULT now();

CREATE TABLE IF NOT EXISTS public.tareas_pendientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion text NOT NULL,
  fecha_ejecucion timestamptz NOT NULL,
  estado text NOT NULL DEFAULT 'pendiente'
);

ALTER TABLE public.tareas_pendientes
  ADD COLUMN IF NOT EXISTS descripcion text,
  ADD COLUMN IF NOT EXISTS fecha_ejecucion timestamptz,
  ADD COLUMN IF NOT EXISTS estado text NOT NULL DEFAULT 'pendiente';

ALTER TABLE public.cuentas DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.transacciones DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.deudas DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.memoria_chat DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.tareas_pendientes DISABLE ROW LEVEL SECURITY;

COMMIT;
